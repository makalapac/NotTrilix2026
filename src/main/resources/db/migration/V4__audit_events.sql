-- Faza 3: audit trag agenta. Svaki poziv alata (tool call), svaki dohvat iz baze znanja i svaki turn razgovora = jedan redak.
-- Redak je samostalan (ime kupca je kopija, ne veza) i ne mijenja se nakon upisa.

CREATE TABLE audit_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    conversation_id   VARCHAR(64),
    customer_id       BIGINT,
    customer_name     VARCHAR(100),
    channel           VARCHAR(10)   NOT NULL,   -- CHAT (kasnije VOICE, PHONE)
    event_type        VARCHAR(20)   NOT NULL,   -- TOOL_CALL | KB_RETRIEVAL | CHAT_TURN
    operation         VARCHAR(64)   NOT NULL,   -- naziv alata / retrieve / turn
    input             VARCHAR(1000),            -- argumenti alata ili poruka kupca
    outcome           VARCHAR(30)   NOT NULL,   -- OK | DENIED | CONFIRMATION_REQUIRED | ERROR
    detail            VARCHAR(2000),            -- rezultat alata / razlog odbijanja / odgovor agenta
    duration_ms       BIGINT,
    prompt_tokens     INTEGER,
    completion_tokens INTEGER
);
CREATE INDEX idx_audit_events_conversation ON audit_events (conversation_id, id);
CREATE INDEX idx_audit_events_customer ON audit_events (customer_id, id);
