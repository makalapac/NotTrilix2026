-- Phase 3: agent audit trail. Every tool call, every knowledge base retrieval and every conversation turn = one row.
-- A row is self-contained (the customer name is a copy, not a reference) and does not change after insert.

CREATE TABLE audit_events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    conversation_id   VARCHAR(64),
    customer_id       BIGINT,
    customer_name     VARCHAR(100),
    channel           VARCHAR(10)   NOT NULL,   -- CHAT (later VOICE, PHONE)
    event_type        VARCHAR(20)   NOT NULL,   -- TOOL_CALL | KB_RETRIEVAL | CHAT_TURN
    operation         VARCHAR(64)   NOT NULL,   -- tool name / retrieve / turn
    input             VARCHAR(1000),            -- tool arguments or the customer message
    outcome           VARCHAR(30)   NOT NULL,   -- OK | DENIED | CONFIRMATION_REQUIRED | ERROR
    detail            VARCHAR(2000),            -- tool result / denial reason / agent reply
    duration_ms       BIGINT,
    prompt_tokens     INTEGER,
    completion_tokens INTEGER
);
CREATE INDEX idx_audit_events_conversation ON audit_events (conversation_id, id);
CREATE INDEX idx_audit_events_customer ON audit_events (customer_id, id);
