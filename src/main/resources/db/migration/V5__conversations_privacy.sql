-- Faza 5: razgovori kao zapis (za analizu i prava kupca), analiza razgovora, prijedlozi za bazu znanja (samoucenje),
-- privole kupca (GDPR). Osobni podaci u ovim tablicama imaju rok cuvanja (nottrilix.privacy.*) i brisu se na zahtjev kupca.

-- Jedan razgovor kupca s agentom (chat ili glas). Turnovi su u audit_events (CHAT_TURN); ovdje je okvir razgovora.
CREATE TABLE conversations (
    id            VARCHAR(64) PRIMARY KEY,               -- conversationId iz agenta
    customer_id   BIGINT REFERENCES customers (id),      -- NULL nakon brisanja na zahtjev kupca (anonimizirano)
    channel       VARCHAR(10)  NOT NULL,                  -- CHAT | VOICE (kanal zadnjeg turna)
    status        VARCHAR(20)  NOT NULL,                  -- OPEN | ANALYZED | ERASED
    started_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_turn_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    turns         INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_conversations_customer ON conversations (customer_id, last_turn_at);
CREATE INDEX idx_conversations_status ON conversations (status, last_turn_at);

-- Sto je model zakljucio o razgovoru (iz pseudonimiziranog transkripta). Jedan redak po razgovoru; ponovna analiza ga zamjenjuje.
CREATE TABLE conversation_analyses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id   VARCHAR(64)  NOT NULL UNIQUE REFERENCES conversations (id) ON DELETE CASCADE,
    customer_id       BIGINT,                              -- kopija radi filtriranja; NULL nakon anonimizacije
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    model             VARCHAR(60)  NOT NULL,
    category          VARCHAR(20)  NOT NULL,               -- KUPNJA | POVRAT | KOD_NE_RADI | BLOKADA | INFORMACIJA | OSTALO
    outcome           VARCHAR(20)  NOT NULL,               -- RIJESENO | NERIJESENO | ESKALIRANO | ODUSTAO
    sentiment         VARCHAR(20)  NOT NULL,               -- POZITIVNO | NEUTRALNO | NEGATIVNO
    quality_score     INTEGER      NOT NULL,               -- 1..5 (kako je agent vodio razgovor)
    rules_followed    BOOLEAN      NOT NULL,
    summary           VARCHAR(1000) NOT NULL,
    knowledge_gaps    VARCHAR(2000),                        -- JSON popis pitanja na koja baza znanja nije imala odgovor
    improvement_notes VARCHAR(2000),                        -- sto bi agent mogao bolje
    turns             INTEGER      NOT NULL,
    tool_calls        INTEGER      NOT NULL,
    prompt_tokens     INTEGER,
    completion_tokens INTEGER,
    duration_ms       BIGINT
);

-- Samoucenje: rupa u znanju iz razgovora -> prijedlog odlomka baze znanja -> admin odobri ili odbije.
-- Odobreni prijedlog ulazi u vector_store (izvor "nauceno-<id>") i vrijedi za sve buduce razgovore. Bez osobnih podataka.
CREATE TABLE kb_suggestions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    conversation_id VARCHAR(64),                            -- odakle je prijedlog potekao (moze biti obrisan)
    question        VARCHAR(500)  NOT NULL,                 -- pitanje kupca, poopceno
    answer          VARCHAR(2000) NOT NULL,                 -- nacrt odgovora (model) -> konacni tekst (admin)
    status          VARCHAR(20)   NOT NULL,                 -- PROPOSED | APPROVED | REJECTED
    decided_at      TIMESTAMP(6) WITH TIME ZONE,
    decided_by      VARCHAR(100)
);
CREATE INDEX idx_kb_suggestions_status ON kb_suggestions (status, created_at);

-- Privole kupca (GDPR cl. 7): sto je kupac prihvatio, kada i koju verziju teksta. Povlacenje = withdrawn_at.
CREATE TABLE consents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT       NOT NULL REFERENCES customers (id),
    type         VARCHAR(20)  NOT NULL,                     -- VOICE
    text_version VARCHAR(20)  NOT NULL,                     -- verzija teksta privole koju je kupac vidio
    given_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    withdrawn_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_consents_customer ON consents (customer_id, type);
