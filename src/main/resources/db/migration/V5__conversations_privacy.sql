-- Phase 5: conversations as records (for analysis and customer rights), conversation analysis, knowledge base suggestions (self-learning),
-- customer consents (GDPR). Personal data in these tables has a retention period (nottrilix.privacy.*) and is erased at the customer's request.

-- One customer conversation with the agent (chat or voice). Turns are in audit_events (CHAT_TURN); this is the conversation record.
CREATE TABLE conversations (
    id            VARCHAR(64) PRIMARY KEY,               -- conversationId from the agent
    customer_id   BIGINT REFERENCES customers (id),      -- NULL after erasure at the customer's request (anonymized)
    channel       VARCHAR(10)  NOT NULL,                  -- CHAT | VOICE (channel of the last turn)
    status        VARCHAR(20)  NOT NULL,                  -- OPEN | ANALYZED | ERASED
    started_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_turn_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    turns         INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_conversations_customer ON conversations (customer_id, last_turn_at);
CREATE INDEX idx_conversations_status ON conversations (status, last_turn_at);

-- What the model concluded about the conversation (from the pseudonymized transcript). One row per conversation; a re-analysis replaces it.
CREATE TABLE conversation_analyses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id   VARCHAR(64)  NOT NULL UNIQUE REFERENCES conversations (id) ON DELETE CASCADE,
    customer_id       BIGINT,                              -- copy for filtering; NULL after anonymization
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    model             VARCHAR(60)  NOT NULL,
    category          VARCHAR(20)  NOT NULL,               -- KUPNJA | POVRAT | KOD_NE_RADI | BLOKADA | INFORMACIJA | OSTALO
    outcome           VARCHAR(20)  NOT NULL,               -- RIJESENO | NERIJESENO | ESKALIRANO | ODUSTAO
    sentiment         VARCHAR(20)  NOT NULL,               -- POZITIVNO | NEUTRALNO | NEGATIVNO
    quality_score     INTEGER      NOT NULL,               -- 1..5 (how well the agent handled the conversation)
    rules_followed    BOOLEAN      NOT NULL,
    summary           VARCHAR(1000) NOT NULL,
    knowledge_gaps    VARCHAR(2000),                        -- JSON list of questions the knowledge base had no answer for
    improvement_notes VARCHAR(2000),                        -- what the agent could do better
    turns             INTEGER      NOT NULL,
    tool_calls        INTEGER      NOT NULL,
    prompt_tokens     INTEGER,
    completion_tokens INTEGER,
    duration_ms       BIGINT
);

-- Self-learning: knowledge gap from a conversation -> proposed knowledge base section -> admin approves or rejects.
-- An approved suggestion goes into vector_store (source "nauceno-<id>") and applies to all future conversations. No personal data.
CREATE TABLE kb_suggestions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    conversation_id VARCHAR(64),                            -- where the suggestion came from (may have been erased)
    question        VARCHAR(500)  NOT NULL,                 -- the customer's question, generalized
    answer          VARCHAR(2000) NOT NULL,                 -- draft answer (model) -> final text (admin)
    status          VARCHAR(20)   NOT NULL,                 -- PROPOSED | APPROVED | REJECTED
    decided_at      TIMESTAMP(6) WITH TIME ZONE,
    decided_by      VARCHAR(100)
);
CREATE INDEX idx_kb_suggestions_status ON kb_suggestions (status, created_at);

-- Customer consents (GDPR Art. 7): what the customer accepted, when and which text version. Withdrawal = withdrawn_at.
CREATE TABLE consents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT       NOT NULL REFERENCES customers (id),
    type         VARCHAR(20)  NOT NULL,                     -- VOICE
    text_version VARCHAR(20)  NOT NULL,                     -- version of the consent text the customer saw
    given_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    withdrawn_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_consents_customer ON consents (customer_id, type);
