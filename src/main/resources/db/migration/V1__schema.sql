CREATE EXTENSION IF NOT EXISTS pgcrypto;  -- bcrypt (crypt/gen_salt) za lozinke u seedu

CREATE TABLE customers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,  -- ujedno korisnicko ime za prijavu u shop
    phone         VARCHAR(30),
    password_hash VARCHAR(100) NOT NULL          -- bcrypt
);

-- Korisnici admin/support konzole
CREATE TABLE admin_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,         -- bcrypt
    name          VARCHAR(100) NOT NULL
);

-- Proizvod = brend + denominacija (npr. "Steam Wallet 25 EUR")
CREATE TABLE products (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category         VARCHAR(20)   NOT NULL,  -- TELEKOM | GAMING
    brand            VARCHAR(20)   NOT NULL,  -- A1 | HT | STEAM | SONY | XBOX
    name             VARCHAR(100)  NOT NULL,
    serial_prefix    VARCHAR(8)    NOT NULL,
    denomination_eur NUMERIC(10,2) NOT NULL,
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    UNIQUE (brand, denomination_eur)
);

-- Zaliha: unaprijed generirani bonovi (serijski broj + aktivacijski kod)
CREATE TABLE vouchers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT       NOT NULL REFERENCES products (id),
    serial_number VARCHAR(32)  NOT NULL UNIQUE,
    code          VARCHAR(32)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,     -- AVAILABLE | SOLD | REDEEMED | BLOCKED
    sold_at       TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_vouchers_product_status ON vouchers (product_id, status);

-- Kupnja: jedan bon po transakciji
CREATE TABLE transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    channel     VARCHAR(10)   NOT NULL,      -- WEB | POS
    status      VARCHAR(20)   NOT NULL,      -- COMPLETED | REFUNDED
    customer_id BIGINT        NOT NULL REFERENCES customers (id),
    product_id  BIGINT        NOT NULL REFERENCES products (id),
    voucher_id  BIGINT        NOT NULL UNIQUE REFERENCES vouchers (id),
    amount_eur  NUMERIC(10,2) NOT NULL,
    refunded_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_transactions_customer ON transactions (customer_id, created_at);

-- Podrska: prijave kupaca (otvara ih support po pozivu/mailu)
CREATE TABLE support_tickets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status         VARCHAR(20)   NOT NULL,   -- OPEN | RESOLVED
    customer_id    BIGINT        NOT NULL REFERENCES customers (id),
    transaction_id BIGINT        REFERENCES transactions (id),
    subject        VARCHAR(200)  NOT NULL,
    description    VARCHAR(2000),
    resolution     VARCHAR(2000),
    resolved_at    TIMESTAMP(6) WITH TIME ZONE
);
